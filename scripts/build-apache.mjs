// Prepares dist/client for a private LiteSpeed/Apache server with PHP + MySQL
// (run via `pnpm build:server-host` after the normal build).
// - Generates .htaccess from vercel.json, so redirects, security headers and caching
//   are defined once and stay identical on both hosting options.
// - Copies the PHP form endpoint (hosting/php/api) into dist/client/api.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist/client");
const vercel = JSON.parse(fs.readFileSync(path.join(root, "vercel.json"), "utf8"));
const forceHttps = process.env.APACHE_FORCE_HTTPS !== "false";

if (!fs.existsSync(path.join(dist, "index.html"))) {
  console.error("✖ Run `pnpm build` first.");
  process.exit(1);
}

// ── Redirects (vercel.json source → mod_rewrite pattern) ────
const escape = (s) => s.replace(/[.+?^${}()|[\]\\]/g, "\\$&");
const seen = new Set();
const redirects = [];
for (const r of vercel.redirects) {
  let src = r.source.replace(/^\//, "").replace(/\/$/, "");
  let pattern;
  if (/:(path|slug)\*$/.test(src)) pattern = `^${escape(src.replace(/\/?:(path|slug)\*$/, ""))}(/.*)?$`;
  else pattern = `^${escape(src)}/?$`;
  if (seen.has(pattern)) continue;
  seen.add(pattern);
  redirects.push(`RewriteRule ${pattern} ${r.destination} [R=${r.statusCode ?? 301},L]`);
}

// ── Headers ─────────────────────────────────────────────────
const stripVercel = (v) =>
  v
    .split(";")
    .map((d) => d.trim().split(/\s+/).filter((t) => !/vercel\.(live|com)|pusher\.com/.test(t)).join(" "))
    .filter((d) => d && !/^frame-src$/.test(d))
    .join("; ");
const headerLine = (h) => `  Header always set ${h.key} "${(h.key === "Content-Security-Policy" ? stripVercel(h.value) : h.value).replace(/"/g, '\\"')}"`;
const siteHeaders = vercel.headers.find((h) => h.source.startsWith("/((?!admin)")).headers.filter((h) => forceHttps || h.key !== "Strict-Transport-Security");
const adminHeaders = vercel.headers.find((h) => h.source.startsWith("/admin")).headers.filter((h) => forceHttps || h.key !== "Strict-Transport-Security");

const htaccess = `# Generated by scripts/build-apache.mjs from vercel.json — edit vercel.json, not this file.
# For LiteSpeed or Apache 2.4 with mod_rewrite and mod_headers (standard on cPanel hosting).

Options -Indexes -MultiViews
DirectoryIndex index.html
DirectorySlash Off
ErrorDocument 404 /404.html
AddDefaultCharset utf-8
AddType application/manifest+json .webmanifest
AddType font/woff2 .woff2
AddType image/webp .webp
AddType image/svg+xml .svg
AddType video/mp4 .mp4

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # Never serve dot-files or folders, except /.well-known (security.txt, SSL validation)
  RewriteRule (^|/)\\.(?!well-known/) - [F,L]
${
  forceHttps
    ? `
  # HTTPS and the bare domain (no www)
  RewriteCond %{HTTPS} !=on [OR]
  RewriteCond %{HTTP_HOST} ^www\\. [NC]
  RewriteCond %{HTTP_HOST} ^(?:www\\.)?(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [R=301,L]
`
    : ""
}
  # Old WordPress addresses → new pages (301)
  ${redirects.join("\n  ")}

  # Canonical URLs have no trailing slash
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteRule ^(.+)/$ /$1 [R=301,L]

  # Form endpoint
  RewriteRule ^api/forms$ api/forms.php [L]

  # Clean URLs: /news/story → /news/story/index.html
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{DOCUMENT_ROOT}/$1/index.html -f
  RewriteRule ^(.+)$ $1/index.html [L]
</IfModule>

<IfModule mod_headers.c>
${siteHeaders.map(headerLine).join("\n")}

  # Hashed files never change; HTML always revalidates
  <FilesMatch "\\.(js|css|woff2|webp)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(jpg|png|svg|ico|mp4|webmanifest)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml application/javascript text/javascript application/json image/svg+xml application/manifest+json
</IfModule>
`;
fs.writeFileSync(path.join(dist, ".htaccess"), htaccess);

// /admin gets the editor's own (slightly wider) Content-Security-Policy
fs.writeFileSync(
  path.join(dist, "admin/.htaccess"),
  `# Generated by scripts/build-apache.mjs\n<IfModule mod_headers.c>\n${adminHeaders.map(headerLine).join("\n")}\n  Header set Cache-Control "no-cache"\n</IfModule>\n`,
);

// PHP form endpoint
const apiSrc = path.join(root, "hosting/php/api");
const apiOut = path.join(dist, "api");
fs.mkdirSync(apiOut, { recursive: true });
for (const f of fs.readdirSync(apiSrc)) fs.copyFileSync(path.join(apiSrc, f), path.join(apiOut, f));

console.log(`server-host bundle ready: dist/client (.htaccess with ${redirects.length} redirects, PHP form endpoint in /api)`);
